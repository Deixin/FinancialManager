import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
// Match the pinned JavaScript Unicode categories exactly in Rust, without a
// new runtime dependency. Generated from the platform used by the shared gate.
const ranges = [];
let start = null;
for (let n = 0; n <= 0x110000; n++) {
  const matches = n < 0x110000 && /\p{Cf}/u.test(String.fromCodePoint(n));
  if (matches && start === null) start = n;
  if (!matches && start !== null) {
    ranges.push([start, n - 1]);
    start = null;
  }
}
const source =
  '// Generated by infra/import-files-desktop/generate.mjs.\n' +
  'pub fn is_format(c: char) -> bool {\n    matches!(c as u32,\n' +
  ranges
    .map(([a, b]) => `        0x${a.toString(16)}..=0x${b.toString(16)}`)
    .join(' |\n') +
  '\n    )\n}\n';
const output = fileURLToPath(
  new URL('../../apps/desktop/src-tauri/src/file_unicode.rs', import.meta.url),
);
const text = execFileSync('rustfmt', ['--edition', '2024'], {
  input: source,
  encoding: 'utf8',
  windowsHide: true,
});
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== text) throw Error('FILE_UNICODE_STALE');
} else writeFileSync(output, text);
