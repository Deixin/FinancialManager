import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../', import.meta.url),
  read = (name) => readFileSync(new URL(name, root), 'utf8');
const folder = 'packages/storage-schema/sqlite/migrations/';
const entries = [
  {
    version: 1,
    name: 'financial-core',
    up: '0001-financial-core.sql',
    down: null,
  },
  {
    version: 2,
    name: 'balance-reference-lookup',
    up: '0002-balance-reference-lookup.up.sql',
    down: '0002-balance-reference-lookup.down.sql',
  },
];
entries.push({
  version: 3,
  name: 'import-ledger',
  up: '0003-import-ledger.up.sql',
  down: '0003-import-ledger.down.sql',
});
const rows = entries.map((entry) => {
  const up = read(folder + entry.up),
    down = entry.down ? read(folder + entry.down) : null;
  const checksum = createHash('sha256')
    .update(
      entry.version === 1
        ? up
        : JSON.stringify([entry.version, entry.name, up, down, false]),
    )
    .digest('hex');
  return `    Migration { version: ${entry.version}, name: "${entry.name}", up: include_str!("../../../../${folder + entry.up}"), down: ${entry.down ? 'Some(include_str!("../../../../' + folder + entry.down + '"))' : 'None'}, checksum: "${checksum}" },`;
});
const output = `// Generated by infra/local-workspaces/generate.mjs. Do not edit.
#[rustfmt::skip]
const CATALOG: [Migration; ${entries.length}] = [
${rows.join('\n')}
];
`;
const file = new URL('apps/desktop/src-tauri/src/migration_catalog.rs', root);
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== output)
    throw Error('NATIVE_CATALOG_DRIFT');
} else writeFileSync(file, output);
console.log('Native product migration catalog OK.');
