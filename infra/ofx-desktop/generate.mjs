import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
const read = (p) =>
  readFileSync(new URL('../../' + p, import.meta.url), 'utf8');
const table = read('packages/importers/src/ofx-reader.ts')
  .split('= {')[1]
  .split('\n};')[0];
const entries = [...table.matchAll(/([A-Z][A-Z0-9]*):\s*\[([^\]]+)\]/g)].map(
  (m) => [m[1], [...m[2].matchAll(/'([A-Z][A-Z0-9]*)'/g)].map((v) => v[1])],
);
const types = [
  ...read('packages/importers/src/ofx-contract.ts')
    .split('export const ofxTransactionTypes')[1]
    .split('] as const')[0]
    .matchAll(/'([A-Z]+)'/g),
].map((m) => m[1]);
assert.equal(entries.length, 17);
assert.equal(types.length, 17);
const source =
  '// Generated by infra/ofx-desktop/generate.mjs; shared OFX schema only.\n' +
  "pub fn children(name: &str) -> Option<&'static [&'static str]> { match name {\n" +
  entries
    .map(
      ([name, tags]) =>
        JSON.stringify(name) +
        ' => Some(&[' +
        tags.map((t) => JSON.stringify(t)).join(',') +
        ']),',
    )
    .join('\n') +
  '\n_ => None, }}\n' +
  'pub const TYPES: &[&str] = &[' +
  types.map((t) => JSON.stringify(t)).join(',') +
  '];\n';
const formatted = execFileSync(
  'rustfmt',
  ['--edition', '2024', '--emit', 'stdout'],
  { input: source, encoding: 'utf8', windowsHide: true },
).replaceAll('\r\n', '\n');
const file = new URL(
  '../../apps/desktop/src-tauri/src/ofx_schema.rs',
  import.meta.url,
);
if (process.argv.includes('--check'))
  assert.equal(readFileSync(file, 'utf8').replaceAll('\r\n', '\n'), formatted);
else writeFileSync(file, formatted);
