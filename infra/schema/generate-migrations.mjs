import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
const directory = new URL('../../packages/storage-schema/', import.meta.url);
const read = (name) => readFileSync(new URL(name, directory), 'utf8');
const entry = {
  version: 2,
  name: 'balance-reference-lookup',
  up: read('sqlite/migrations/0002-balance-reference-lookup.up.sql'),
  down: read('sqlite/migrations/0002-balance-reference-lookup.down.sql'),
  destructive: false,
};
entry.checksum = createHash('sha256')
  .update(
    JSON.stringify([
      entry.version,
      entry.name,
      entry.up,
      entry.down,
      entry.destructive,
    ]),
  )
  .digest('hex');
const file = new URL('src/generated-migrations.ts', directory);
const output = await format(
  `// Generated by infra/schema/generate-migrations.mjs. No financial data.
import { sqliteMigration, sqliteMigrationSha256 } from './generated.js';
import type { Migration } from './migration-plan.js';
export const sqliteCatalog: readonly Migration[] = Object.freeze([
Object.freeze({ version:1, name:'financial-core', up:sqliteMigration, down:null, destructive:false, checksum:sqliteMigrationSha256 }),
Object.freeze(${JSON.stringify(entry)})]);`,
  { ...(await resolveConfig(fileURLToPath(file))), parser: 'typescript' },
);
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== output)
    throw new Error('MIGRATION_GENERATION_DRIFT');
} else writeFileSync(file, output);
console.log('US-022 migration catalog OK.');
