import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { _ } from 'ajv/dist/compile/codegen/index.js';
import ts from 'typescript';
import prettier from 'prettier';

const root = fileURLToPath(new URL('../../', import.meta.url));
const rootId = 'urn:financial-manager:contracts:v1';
const banner = '// Generated by pnpm contracts:generate. Do not edit.\n';
const ref = (name) => ({ $ref: `${rootId}#/$defs/${name}` });
const object = (properties, required = []) => ({
  type: 'object',
  additionalProperties: false,
  properties,
  required,
});

function localRefs(value) {
  if (Array.isArray(value)) return value.map(localRefs);
  if (value === null || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.entries(value).map(([key, child]) => [
      key,
      key === '$ref' &&
      typeof child === 'string' &&
      child.startsWith('#/components/schemas/')
        ? `${rootId}#/$defs/${child.slice('#/components/schemas/'.length)}`
        : localRefs(child),
    ]),
  );
}

export async function renderContracts(document) {
  // This generator intentionally accepts a local, finite contract only. No remote resolution.
  const walk = (value) => {
    if (value === null || typeof value !== 'object') return;
    if (
      typeof value.$ref === 'string' &&
      !value.$ref.startsWith('#/components/')
    )
      throw new Error('External contract reference refused');
    Object.values(value).forEach(walk);
  };
  walk(document);
  if (
    document.openapi !== '3.1.1' ||
    !/^1\.\d+\.\d+$/.test(document.info.version)
  )
    throw new Error('Unsupported contract version');
  const ast = await openapiTS(document, {
    immutable: true,
    inject: "import type { MoneyMinor } from '@financial-manager/domain';",
    transform(schema) {
      if (schema.format === 'money-minor')
        return ts.factory.createTypeReferenceNode('MoneyMinor');
    },
  });
  const ajv = new Ajv2020({
    strict: true,
    allErrors: false,
    inlineRefs: false,
    code: {
      source: true,
      esm: true,
      lines: true,
      formats: _`formatValidators`,
    },
  });
  // Actual predicates are imported in generated code; compilation does not execute them.
  for (const format of [
    'money-minor',
    'positive-i64',
    'uuid',
    'date',
    'date-time',
  ])
    ajv.addFormat(format, { type: 'string', validate: () => true });
  ajv.addSchema({ $id: rootId, $defs: localRefs(document.components.schemas) });
  const validators = {};
  const register = (name, schema) => {
    const id = `${rootId}:${name}`;
    ajv.addSchema({ $id: id, ...schema });
    ajv.getSchema(id);
    validators[name] = id;
  };
  for (const name of [
    'MoneyMinor',
    'Version',
    'Uuid',
    'FinancialDate',
    'UtcInstant',
    'ApiError',
  ])
    register(`validate${name}`, ref(name));
  const sdk = [
    banner,
    "import type { operations } from './schema.js';",
    "import { createExecutor, parseRequest } from '../transport.js';",
    "import type { ClientConfig, ApiResult } from '../transport.js';",
  ];
  const types = [],
    methods = [],
    names = new Set();
  for (const [route, item] of Object.entries(document.paths)) {
    for (const [method, operation] of Object.entries(item)) {
      if (!['get', 'post'].includes(method))
        throw new Error('Unsupported contract method');
      const id = operation.operationId;
      if (
        !/^[a-z][A-Za-z0-9]*$/.test(id) ||
        names.has(id) ||
        !route.startsWith('/v1/workspaces/{workspaceId}/')
      )
        throw new Error('Invalid operation');
      names.add(id);
      const typeName = id[0].toUpperCase() + id.slice(1) + 'Input';
      const groups = { path: {}, query: {}, headers: {} },
        required = { path: [], query: [], headers: [] };
      for (const paramRef of operation.parameters ?? []) {
        const param = paramRef.$ref
          ? document.components.parameters[paramRef.$ref.split('/').at(-1)]
          : paramRef;
        const group = param.in === 'header' ? 'headers' : param.in;
        if (!Object.hasOwn(groups, group))
          throw new Error('Unsupported parameter');
        groups[group][param.name] = localRefs(param.schema);
        if (param.required) required[group].push(param.name);
      }
      const props = {},
        must = [],
        fields = [];
      for (const group of Object.keys(groups)) {
        if (!Object.keys(groups[group]).length) continue;
        props[group] = object(groups[group], required[group]);
        const mandatory = required[group].length > 0;
        if (mandatory) must.push(group);
        const operationGroup = group === 'headers' ? 'header' : group;
        fields.push(
          `readonly ${group}${mandatory ? '' : '?'}: NonNullable<operations['${id}']['parameters']['${operationGroup}']>;`,
        );
      }
      if (operation.requestBody) {
        props.body = localRefs(
          operation.requestBody.content['application/json'].schema,
        );
        must.push('body');
        fields.push(
          `readonly body: operations['${id}']['requestBody']['content']['application/json'];`,
        );
      }
      register(`request${id}`, object(props, must));
      const successes = Object.keys(operation.responses).filter((status) =>
        /^2\d\d$/.test(status),
      );
      if (successes.length !== 1 || !operation.responses.default)
        throw new Error('One success and standard error required');
      const status = successes[0];
      register(
        `response${id}`,
        localRefs(
          operation.responses[status].content['application/json'].schema,
        ),
      );
      sdk.push(
        `import { request${id}, response${id} } from './validators.js';`,
      );
      types.push(`export type ${typeName} = { ${fields.join('\n')} };`);
      types.push(
        `export function parse${typeName}(value: unknown): ${typeName} { return parseRequest<${typeName}>(request${id}, value); }`,
      );
      const responseType = `operations['${id}']['responses'][${status}]['content']['application/json']`;
      methods.push(
        `${id}: (input: ${typeName}): Promise<ApiResult<${responseType}>> => execute<${responseType}>({ id: '${id}', method: '${method.toUpperCase()}', path: '${route}', status: ${status}, request: request${id}, response: response${id} }, input),`,
      );
    }
  }
  sdk.push(
    ...types,
    `export function createV1Client(config: ClientConfig) { const execute = createExecutor(config); return Object.freeze({ ${methods.join('\n')} }); }`,
    'export type V1Client = ReturnType<typeof createV1Client>;',
  );
  let validation = standaloneCode(ajv, validators);
  if (/\brequire\s*\(/.test(validation))
    throw new Error('Generated validator needs a runtime dependency');
  validation =
    banner +
    '/* eslint-disable -- Generated validation code. */\n' +
    "import { formatValidators } from '../formats.js';\n" +
    validation;
  const files = {
    'schema.ts': banner + astToString(ast),
    'sdk.ts': sdk.join('\n'),
    'validators.js': validation,
  };
  const config = await prettier.resolveConfig(path.join(root, 'package.json'));
  return Object.fromEntries(
    await Promise.all(
      Object.entries(files).map(async ([name, content]) => [
        name,
        await prettier.format(content, {
          ...config,
          parser: name.endsWith('.ts') ? 'typescript' : 'babel',
        }),
      ]),
    ),
  );
}

export async function generateContracts({ check = false } = {}) {
  const document = JSON.parse(
    await readFile(
      path.join(root, 'packages/contracts/openapi/v1.json'),
      'utf8',
    ),
  );
  const files = await renderContracts(document);
  const output = path.join(root, 'packages/contracts/src/generated');
  if (!check) await mkdir(output, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const filename = path.join(output, name);
    if (check) {
      if ((await readFile(filename, 'utf8')) !== content)
        throw new Error('Contract generation drift: ' + name);
    } else await writeFile(filename, content, 'utf8');
  }
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await generateContracts({ check: process.argv.includes('--check') });
  console.log(
    process.argv.includes('--check')
      ? 'Contracts generation OK.'
      : 'Contracts generated.',
  );
}
